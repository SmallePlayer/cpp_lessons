// =============================================================================
// Урок 5: Циклы (for, while, do-while)
// =============================================================================
// Темы:
//   - Цикл while
//   - Цикл do-while (нет в Python!)
//   - Цикл for (классический)
//   - Range-based for (аналог Python for...in)
//   - break и continue
//   - Вложенные циклы
//   - Бесконечные циклы
//
// Аналогия с Python:
//   Python: for i in range(10):     →  C++: for (int i = 0; i < 10; ++i)
//   Python: for item in list:       →  C++: for (auto& item : vec) { }
//   Python: while condition:        →  C++: while (condition) { }
//   Python: (нет аналога)           →  C++: do { } while (condition);
// =============================================================================

#include <iostream>
#include <vector>
#include <string>

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << "   Урок 5: Циклы" << std::endl;
    std::cout << "========================================\n" << std::endl;

    // =====================================================================
    // 1. ЦИКЛ while
    // =====================================================================
    // Выполняет тело цикла, ПОКА условие ИСТИННО.
    // Условие проверяется ДО каждой итерацией.
    // Если условие сразу ложно — тело НЕ выполнится ни разу.
    //
    // while (условие) {
    //     // тело цикла
    // }
    //
    // Python: while condition:
    // C++:    while (condition) { }

    std::cout << "--- 1. while ---" << std::endl;

    int count{1};
    while (count <= 5) {
        std::cout << "count = " << count << std::endl;
        ++count;  // Не забудьте изменять переменную! Иначе — бесконечный цикл!
    }
    std::cout << "Цикл while завершён, count = " << count << std::endl;
    std::cout << std::endl;

    // Пример: сумма чисел от 1 до 100
    int sum{0};
    int n{1};
    while (n <= 100) {
        sum += n;
        ++n;
    }
    std::cout << "Сумма 1..100 = " << sum << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 2. ЦИКЛ do-while
    // =====================================================================
    // Похож на while, НО тело выполняется ХОТЯ БЫ ОДИН РАЗ!
    // Условие проверяется ПОСЛЕ каждой итерации.
    //
    // do {
    //     // тело цикла
    // } while (условие);   // <-- ТОЧКА С ЗАПЯТОЙ ОБЯЗАТЕЛЬНА!
    //
    // В Python НЕТ do-while! Приходится делать:
    //   while True:
    //       ...
    //       if not condition: break
    //
    // Типичное использование: валидация ввода пользователя
    // (нужно запросить хотя бы один раз)

    std::cout << "--- 2. do-while ---" << std::endl;

    int attempt{0};
    do {
        ++attempt;
        std::cout << "Попытка #" << attempt << std::endl;
    } while (attempt < 3);
    std::cout << "do-while завершён после " << attempt << " попыток" << std::endl;
    std::cout << std::endl;

    // do-while с условием, которое сразу ложно:
    int zero_val{0};
    do {
        std::cout << "do-while: выполнится хотя бы раз! (zero_val = " << zero_val << ")" << std::endl;
    } while (zero_val > 100);  // Условие ложно, но тело выполнилось!
    std::cout << std::endl;

    // =====================================================================
    // 3. ЦИКЛ for (КЛАССИЧЕСКИЙ)
    // =====================================================================
    // for (инициализация; условие; обновление) {
    //     // тело цикла
    // }
    //
    // Инициализация — выполняется ОДИН раз перед началом
    // Условие — проверяется ДО каждой итерацией
    // Обновление — выполняется ПОСЛЕ каждой итерации
    //
    // Python: for i in range(start, stop, step):
    // C++:    for (int i = start; i < stop; i += step) { }
    //
    // Эквивалентности:
    //   range(5)       →  for (int i = 0; i < 5; ++i)
    //   range(1, 10)   →  for (int i = 1; i < 10; ++i)
    //   range(0, 10, 2)→  for (int i = 0; i < 10; i += 2)
    //   range(10, 0, -1)→ for (int i = 10; i > 0; --i)

    std::cout << "--- 3. for (классический) ---" << std::endl;

    // Простой цикл 0..4
    std::cout << "for 0..4: ";
    for (int i{0}; i < 5; ++i) {
        std::cout << i << " ";
    }
    std::cout << std::endl;

    // С шагом 2
    std::cout << "Чётные 0..10: ";
    for (int i{0}; i <= 10; i += 2) {
        std::cout << i << " ";
    }
    std::cout << std::endl;

    // Обратный отсчёт
    std::cout << "Обратный: ";
    for (int i{5}; i >= 1; --i) {
        std::cout << i << " ";
    }
    std::cout << "Пуск!" << std::endl;

    // Таблица умножения:
    std::cout << "\nТаблица умножения 5:" << std::endl;
    for (int i{1}; i <= 10; ++i) {
        std::cout << "  5 x " << i << " = " << (5 * i) << std::endl;
    }
    std::cout << std::endl;

    // =====================================================================
    // 4. RANGE-BASED FOR (C++11)
    // =====================================================================
    // for (тип элемент : контейнер) {
    //     // используем элемент
    // }
    //
    // Это ТОЧНЫЙ аналог Python: for item in list:
    //
    // Варианты:
    //   for (int x : vec)        — КОПИЯ каждого элемента
    //   for (int& x : vec)       — ССЫЛКА (можно изменять!)
    //   for (const int& x : vec) — КОНСТАНТНАЯ ССЫЛКА (без копирования)
    //   for (auto x : vec)       — тип определяется автоматически
    //   for (const auto& x : vec)— ЛУЧШИЙ для чтения

    std::cout << "--- 4. Range-based for ---" << std::endl;

    std::vector<int> numbers{10, 20, 30, 40, 50};

    // Чтение элементов (const auto& — рекомендуемый способ):
    std::cout << "Элементы: ";
    for (const auto& num : numbers) {
        std::cout << num << " ";
    }
    std::cout << std::endl;

    // Изменение элементов (auto& — по ссылке):
    for (auto& num : numbers) {
        num *= 2;  // Удваиваем каждый элемент
    }
    std::cout << "После x2: ";
    for (const auto& num : numbers) {
        std::cout << num << " ";
    }
    std::cout << std::endl;

    // Со строками:
    std::vector<std::string> fruits{"яблоко", "банан", "вишня"};
    std::cout << "Фрукты:" << std::endl;
    for (const auto& fruit : fruits) {
        std::cout << "  - " << fruit << std::endl;
    }

    // С инициализатором {} (C++11):
    std::cout << "Числа из {}: ";
    for (int val : {1, 2, 3, 4, 5}) {
        std::cout << val << " ";
    }
    std::cout << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 5. break и continue
    // =====================================================================
    // break    — ПОЛНОСТЬЮ выходит из цикла
    // continue — ПРОПУСКАЕТ остаток итерации и идёт к следующей
    //
    // Работают точно так же, как в Python!
    //
    // ВАЖНО: break и continue действуют только на БЛИЖАЙШИЙ цикл!

    std::cout << "--- 5. break и continue ---" << std::endl;

    // break: ищем первое число > 15
    std::cout << "break (первое > 15): ";
    for (int i{1}; i <= 30; ++i) {
        if (i > 15) {
            std::cout << "-> найдено " << i << "!" << std::endl;
            break;  // Выходим из цикла
        }
        std::cout << i << " ";
    }

    // continue: пропускаем числа, делящиеся на 3
    std::cout << "continue (без кратных 3): ";
    for (int i{1}; i <= 15; ++i) {
        if (i % 3 == 0) {
            continue;  // Пропускаем этот элемент
        }
        std::cout << i << " ";
    }
    std::cout << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 6. ВЛОЖЕННЫЕ ЦИКЛЫ
    // =====================================================================
    std::cout << "--- 6. Вложенные циклы ---" << std::endl;

    // Прямоугольник из звёздочек:
    int rows{3}, cols{5};
    std::cout << "Прямоугольник " << rows << "x" << cols << ":" << std::endl;
    for (int r{0}; r < rows; ++r) {
        for (int c{0}; c < cols; ++c) {
            std::cout << "* ";
        }
        std::cout << std::endl;
    }
    std::cout << std::endl;

    // Треугольник:
    std::cout << "Треугольник:" << std::endl;
    for (int r{1}; r <= 5; ++r) {
        for (int c{0}; c < r; ++c) {
            std::cout << "* ";
        }
        std::cout << std::endl;
    }
    std::cout << std::endl;

    // =====================================================================
    // 7. БЕСКОНЕЧНЫЕ ЦИКЛЫ
    // =====================================================================
    // while (true) { }        — бесконечный цикл (как в Python)
    // for (;;) { }            — тоже бесконечный цикл (идиома C++)
    //
    // Используйте с break для выхода по условию.
    // ОПАСНО: Без break программа зависнет!

    std::cout << "--- 7. Бесконечный цикл с break ---" << std::endl;

    int counter2{0};
    for (;;) {  // Бесконечный цикл
        ++counter2;
        if (counter2 >= 5) {
            std::cout << "Выход из бесконечного цикла на итерации " << counter2 << std::endl;
            break;
        }
        std::cout << "Итерация " << counter2 << std::endl;
    }
    std::cout << std::endl;

    // =====================================================================
    // 8. ПРАКТИКА: Числа Фибоначчи
    // =====================================================================
    std::cout << "--- 8. Числа Фибоначчи ---" << std::endl;

    int fib_count{15};
    long long fib_a{0}, fib_b{1};

    std::cout << "Первые " << fib_count << " чисел Фибоначчи:" << std::endl;
    for (int i{0}; i < fib_count; ++i) {
        std::cout << fib_a << " ";
        long long temp = fib_a + fib_b;
        fib_a = fib_b;
        fib_b = temp;
    }
    std::cout << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 9. ПРАКТИКА: Простые числа
    // =====================================================================
    std::cout << "--- 9. Простые числа до 50 ---" << std::endl;

    std::cout << "Простые числа: ";
    for (int num2{2}; num2 <= 50; ++num2) {
        bool is_prime{true};
        for (int div{2}; div * div <= num2; ++div) {
            if (num2 % div == 0) {
                is_prime = false;
                break;
            }
        }
        if (is_prime) {
            std::cout << num2 << " ";
        }
    }
    std::cout << std::endl;
    std::cout << std::endl;

    std::cout << "========================================" << std::endl;
    std::cout << "  Урок 5 завершён!" << std::endl;
    std::cout << "========================================\n" << std::endl;

    std::cout << "ДОМАШНЕЕ ЗАДАНИЕ:" << std::endl;
    std::cout << "1. Напишите программу для нахождения факториала числа" << std::endl;
    std::cout << "2. Выведите таблицу умножения от 1 до 10" << std::endl;
    std::cout << "3. Реализуйте угадывание числа (do-while)" << std::endl;
    std::cout << "4. Найдите все делители заданного числа" << std::endl;
    std::cout << "5. Нарисуйте ромб из звёздочек" << std::endl;

    return 0;
}
