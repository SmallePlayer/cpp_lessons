// =============================================================================
//  8: Указатели и Ссылки
// =============================================================================
// Темы:
//   - Что такое указатель (pointer)
//   - Адрес переменной: оператор &
//   - Разыменование: оператор *
//   - Нулевой указатель: nullptr
//   - Ссылки (references): int&
//   - Разница между указателями и ссылками
//   - Указатели и массивы
//   - Динамическая память: new и delete
//   - Умные указатели: unique_ptr, shared_ptr
//   - Опасности: висячие указатели, утечки памяти
//
// Аналогия с Python:
//    Все Python переменные — это ссылки на объекты в куче.
//    В C++ вы явно выбираете: стек или куча, указатель или значение.
//   Python: a = [1,2,3]; b = a  — b ссылается на тот же список
//   C++:    int* ptr = &x;      — ptr хранит адрес переменной x
// =============================================================================

#include <iostream>
#include <memory>   // unique_ptr, shared_ptr, make_unique, make_shared
#include <string>
#include <vector>

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << "   8: Указатели и Ссылки" << std::endl;
    std::cout << "========================================\n" << std::endl;

    // =====================================================================
    // 1. С  — Т &
    // =====================================================================
    // Каждая переменная хранится в памяти по определённому адресу.
    // & перед переменной даёт её адрес.
    //
    // Python: id(x) → уникальный идентификатор объекта
    // C++:    &x    → адрес переменной в памяти (0x7fff...)
    //
    // Адрес — это число (номер ячейки памяти).
    // На 64-битной системе адрес = 8 байт.

    std::cout << "--- 1. Адреса переменных ---" << std::endl;

    int x{42};
    double y{3.14};
    char c{'A'};

    std::cout << "x = " << x << ", адрес: " << &x << std::endl;
    std::cout << "y = " << y << ", адрес: " << &y << std::endl;
    std::cout << "c = " << c << ", адрес: " << static_cast<void*>(&c) << std::endl;
    // Для char нужен static_cast<void*>, иначе выведется как строка!
    std::cout << std::endl;

    // =====================================================================
    // 2. Т (POINTERS)
    // =====================================================================
    // Указатель — переменная, которая хранит адрес другой переменной.
    //
    // int* ptr;     — указатель на int (хранит адрес int)
    // double* ptr;  — указатель на double
    // char* ptr;    — указатель на char
    //
    // * при объявлении — "это указатель"
    // * при использовании — "разыменование" (получить значение по адресу)
    //
    //   int x = 42;
    //   int* ptr = &x;     // ptr хранит адрес x
    //   std::cout << *ptr; // 42 (разыменование — значение по адресу)
    //   *ptr = 100;        // Изменяет x через указатель!

    std::cout << "--- 2. Указатели ---" << std::endl;

    int value{42};
    int* ptr = &value;  // ptr указывает на value

    std::cout << "value = " << value << std::endl;
    std::cout << "ptr (адрес) = " << ptr << std::endl;
    std::cout << "*ptr (значение) = " << *ptr << std::endl;

    // Изменение через указатель:
    *ptr = 100;
    std::cout << "После *ptr = 100:" << std::endl;
    std::cout << "  value = " << value << " (изменилось!)" << std::endl;
    std::cout << "  *ptr = " << *ptr << std::endl;

    // Размер указателя (всегда одинаковый на одной платформе):
    std::cout << "sizeof(int*) = " << sizeof(int*) << " байт" << std::endl;
    std::cout << "sizeof(double*) = " << sizeof(double*) << " байт" << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 3. nullptr —  ТЬ
    // =====================================================================
    // nullptr (C++11) — специальное значение "указатель никуда не указывает"
    //
    // Python: None
    // C:      NULL (макрос, = 0)
    // C++:    nullptr (тип-безопасный)
    //
    // Всегда проверяйте указатель на nullptr перед разыменованием!
    // Разыменование nullptr = CRASH (Segmentation Fault)!

    std::cout << "--- 3. nullptr ---" << std::endl;

    int* null_ptr = nullptr;  // Не указывает никуда
    std::cout << "null_ptr = " << null_ptr << std::endl;

    if (null_ptr == nullptr) {
        std::cout << "Указатель = nullptr (никуда не указывает)" << std::endl;
    }

    // Безопасная проверка:
    if (null_ptr != nullptr) {
        std::cout << *null_ptr << std::endl;  //  выполнится
    } else {
        std::cout << "Нельзя разыменовать nullptr!" << std::endl;
    }
    std::cout << std::endl;

    // =====================================================================
    // 4. ССЫ (REFERENCES)
    // =====================================================================
    // Ссылка — это псевдоним (alias) для существующей переменной.
    //
    // int x = 42;
    // int& ref = x;  // ref — это ещё одно имя для x
    //
    // Отличия ссылок от указателей:
    // 1. Ссылка должна быть инициализирована (нет "null ссылки")
    // 2. Ссылку нельзя переназначить на другую переменную
    // 3. Ссылка не занимает дополнительную память (обычно)
    // 4. Синтаксис проще — не нужны * и &
    //
    // Python: a = [1,2,3]; b = a  — b ссылается на тот же объект
    //         (все переменные в Python — это ссылки!)

    std::cout << "--- 4. Ссылки ---" << std::endl;

    int original{42};
    int& ref = original;  // ref — псевдоним для original

    std::cout << "original = " << original << std::endl;
    std::cout << "ref = " << ref << std::endl;

    ref = 100;  // Изменяет original!
    std::cout << "После ref = 100:" << std::endl;
    std::cout << "  original = " << original << std::endl;
    std::cout << "  ref = " << ref << std::endl;
    std::cout << "  Адреса одинаковы: " << &original << " == " << &ref << std::endl;

    // const ссылка — нельзя изменить:
    const int& const_ref = original;
    std::cout << "const_ref = " << const_ref << std::endl;
    // const_ref = 200;  // Ш: нельзя изменить через const ссылку
    std::cout << std::endl;

    // =====================================================================
    // 5. Т vs ССЫ —  Т СЬТЬ
    // =====================================================================
    // Ссылки — предпочтительнее в большинстве случаев:
    //   - араметры функций (const std::string& name)
    //   - Когда не нужен nullptr
    //   - Когда не нужно переназначать
    //
    // Указатели — когда нужно:
    //   - Опциональное значение (может быть nullptr)
    //   - Переназначение на другой объект
    //   - Динамическая память (new/delete)
    //   - Массивы и C-совместимость

    std::cout << "--- 5. Указатели vs Ссылки ---" << std::endl;
    std::cout << "Ссылка: простой псевдоним, безопаснее" << std::endl;
    std::cout << "Указатель: гибче, но опаснее" << std::endl;
    std::cout << "Правило: используйте ссылки, когда можно; указатели, когда нужно" << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 6. СЯ ЯТЬ: new  delete
    // =====================================================================
    //  В C++ вы можете выделять память в куче (heap) вручную.
    //
    // Стек (stack) — автоматическая память:
    //   int x = 42;  // На стеке, удалится при выходе из {}
    //
    // Куча (heap) — ручная память:
    //   int* ptr = new int{42};  // Выделяем в куче
    //   delete ptr;              // Нужно освободить!
    //
    // Если забыть delete — будет утечка памяти (memory leak)!
    //  В Python: сборщик мусора (GC) делает это за вас.
    //  В C++: вы сами отвечаете за память!
    //
    // : не используйте raw new/delete!
    //          спользуйте Ы Т (см. раздел 7)!

    std::cout << "--- 6. new и delete (не рекомендуется!) ---" << std::endl;

    int* heap_int = new int{42};             // Выделяем в куче
    std::cout << "*heap_int = " << *heap_int << std::endl;
    delete heap_int;                          // Освобождаем!
    heap_int = nullptr;                       // Обнуляем после delete!

    // Массив в куче:
    int* heap_arr = new int[5]{10, 20, 30, 40, 50};
    std::cout << "heap_arr: ";
    for (int i = 0; i < 5; ++i) {
        std::cout << heap_arr[i] << " ";
    }
    std::cout << std::endl;
    delete[] heap_arr;  // delete[] для массивов!
    heap_arr = nullptr;
    std::cout << std::endl;

    // =====================================================================
    // 7. Ы Т (Smart Pointers) — C++11
    // =====================================================================
    // Умные указатели автоматически освобождают память!
    // Это лучший способ работы с динамической памятью.
    //
    // std::unique_ptr<T> — единственный владелец. Нельзя копировать!
    //   auto ptr = std::make_unique<int>(42);
    //
    // std::shared_ptr<T> — разделяемый владелец. Считает ссылки.
    //   Память освобождается, когда последний shared_ptr уничтожается.
    //   auto ptr = std::make_shared<int>(42);
    //
    // Python аналогия: С переменные в Python — это shared_ptr с GC!

    std::cout << "--- 7. Умные указатели ---" << std::endl;

    // unique_ptr — единственный владелец:
    {
        auto uptr = std::make_unique<int>(42);
        std::cout << "unique_ptr: *uptr = " << *uptr << std::endl;
        *uptr = 100;
        std::cout << "unique_ptr: *uptr = " << *uptr << std::endl;
        // auto uptr2 = uptr;  // Ошибка! Нельзя копировать!
        auto uptr2 = std::move(uptr);  // Можно переместить
        std::cout << "После move: *uptr2 = " << *uptr2 << std::endl;
        // uptr теперь nullptr!
    }  // uptr2 уничтожается, память освобождается автоматически!

    // shared_ptr — разделяемый владелец:
    {
        auto sptr1 = std::make_shared<std::string>("Hello, Smart!");
        std::cout << "shared_ptr: *sptr1 = " << *sptr1 << std::endl;
        std::cout << "use_count = " << sptr1.use_count() << std::endl;

        {
            auto sptr2 = sptr1;  // Копирование! Теперь 2 владельца.
            std::cout << "use_count (2 владельца) = " << sptr1.use_count() << std::endl;
        }  // sptr2 уничтожается, но строка жива!

        std::cout << "use_count (1 владелец) = " << sptr1.use_count() << std::endl;
    }  // Последний владелец уничтожен → память освобождена!

    // unique_ptr с вектором:
    auto vec_ptr = std::make_unique<std::vector<int>>(std::vector<int>{1, 2, 3, 4, 5});
    std::cout << "unique_ptr<vector>: ";
    for (const auto& v : *vec_ptr) {
        std::cout << v << " ";
    }
    std::cout << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 8. ТС : Связанный список на умных указателях
    // =====================================================================
    std::cout << "--- 8. Практический пример ---" << std::endl;

    // Простой пример: обмен значениями через указатели
    int va{10}, vb{20};
    int* pa = &va;
    int* pb = &vb;
    std::cout << "До: *pa = " << *pa << ", *pb = " << *pb << std::endl;

    // Обмен значений:
    int temp2 = *pa;
    *pa = *pb;
    *pb = temp2;
    std::cout << "После обмена: va = " << va << ", vb = " << vb << std::endl;
    std::cout << std::endl;

    std::cout << "========================================" << std::endl;
    std::cout << "  Урок 8 завершён!" << std::endl;
    std::cout << "========================================\n" << std::endl;

    std::cout << "Я Я Т:" << std::endl;
    std::cout << "1. Напишите функцию, которая возвращает min и max через указатели" << std::endl;
    std::cout << "2. Реализуйте динамический массив с new/delete" << std::endl;
    std::cout << "3. Перепишите задание 2 с unique_ptr" << std::endl;
    std::cout << "4. Создайте функцию, принимающую вектор по ссылке" << std::endl;
    std::cout << "5. Попробуйте shared_ptr с циклической ссылкой" << std::endl;

    return 0;
}