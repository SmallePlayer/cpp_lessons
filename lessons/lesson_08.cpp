// =============================================================================
//  8: казатели и Ссылки
// =============================================================================
// Темы:
//   - то такое указатель (pointer)
//   - дрес переменной: оператор &
//   - азыменование: оператор *
//   - улевой указатель: nullptr
//   - Ссылки (references): int&
//   - азница между указателями и ссылками
//   - казатели и массивы
//   - инамическая память: new и delete
//   - мные указатели: unique_ptr, shared_ptr
//   - пасности: висячие указатели, утечки памяти
//
// налогия с Python:
//    Python С переменные — это ссылки на объекты в куче.
//    C++ вы Я выбираете: стек или куча, указатель или значение.
//   Python: a = [1,2,3]; b = a  — b ссылается на тот же список
//   C++:    int* ptr = &x;      — ptr хранит С переменной x
// =============================================================================

#include <iostream>
#include <memory>   // unique_ptr, shared_ptr, make_unique, make_shared
#include <string>
#include <vector>

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << "   8: казатели и Ссылки" << std::endl;
    std::cout << "========================================\n" << std::endl;

    // =====================================================================
    // 1. С  — Т &
    // =====================================================================
    // аждая переменная хранится в памяти по определённому С.
    // & перед переменной даёт её адрес.
    //
    // Python: id(x) → уникальный идентификатор объекта
    // C++:    &x    → адрес переменной в памяти (0x7fff...)
    //
    // дрес — это число (номер ячейки памяти).
    // а 64-битной системе адрес = 8 байт.

    std::cout << "--- 1. дреса переменных ---" << std::endl;

    int x{42};
    double y{3.14};
    char c{'A'};

    std::cout << "x = " << x << ", адрес: " << &x << std::endl;
    std::cout << "y = " << y << ", адрес: " << &y << std::endl;
    std::cout << "c = " << c << ", адрес: " << static_cast<void*>(&c) << std::endl;
    // ля char нужен static_cast<void*>, иначе выведется как строка!
    std::cout << std::endl;

    // =====================================================================
    // 2. Т (POINTERS)
    // =====================================================================
    // казатель — переменная, которая хранит С другой переменной.
    //
    // int* ptr;     — указатель на int (хранит адрес int)
    // double* ptr;  — указатель на double
    // char* ptr;    — указатель на char
    //
    // * при объявлении — "это указатель"
    // * при использовании — "разыменование" (получить значение по адресу)
    //
    //   int x = 42;
    //   int* ptr = &x;     // ptr хранит адрес x
    //   std::cout << *ptr; // 42 (разыменование — значение по адресу)
    //   *ptr = 100;        // зменяет x через указатель!

    std::cout << "--- 2. казатели ---" << std::endl;

    int value{42};
    int* ptr = &value;  // ptr указывает на value

    std::cout << "value = " << value << std::endl;
    std::cout << "ptr (адрес) = " << ptr << std::endl;
    std::cout << "*ptr (значение) = " << *ptr << std::endl;

    // зменение через указатель:
    *ptr = 100;
    std::cout << "осле *ptr = 100:" << std::endl;
    std::cout << "  value = " << value << " (изменилось!)" << std::endl;
    std::cout << "  *ptr = " << *ptr << std::endl;

    // азмер указателя (всегда одинаковый на одной платформе):
    std::cout << "sizeof(int*) = " << sizeof(int*) << " байт" << std::endl;
    std::cout << "sizeof(double*) = " << sizeof(double*) << " байт" << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 3. nullptr —  ТЬ
    // =====================================================================
    // nullptr (C++11) — специальное значение "указатель никуда не указывает"
    //
    // Python: None
    // C:      NULL (макрос, = 0)
    // C++:    nullptr (тип-безопасный)
    //
    // С проверяйте указатель на nullptr перед разыменованием!
    // азыменование nullptr = CRASH (Segmentation Fault)!

    std::cout << "--- 3. nullptr ---" << std::endl;

    int* null_ptr = nullptr;  // е указывает никуда
    std::cout << "null_ptr = " << null_ptr << std::endl;

    if (null_ptr == nullptr) {
        std::cout << "казатель = nullptr (никуда не указывает)" << std::endl;
    }

    // езопасная проверка:
    if (null_ptr != nullptr) {
        std::cout << *null_ptr << std::endl;  //  выполнится
    } else {
        std::cout << "ельзя разыменовать nullptr!" << std::endl;
    }
    std::cout << std::endl;

    // =====================================================================
    // 4. ССЫ (REFERENCES)
    // =====================================================================
    // Ссылка — это С (alias) для существующей переменной.
    //
    // int x = 42;
    // int& ref = x;  // ref — это ещё одно имя для x
    //
    // тличия ссылок от указателей:
    // 1. Ссылка Я быть инициализирована (нет "null ссылки")
    // 2. Ссылку ЬЯ переназначить на другую переменную
    // 3. Ссылка  занимает дополнительную память (обычно)
    // 4. Синтаксис проще — не нужны * и &
    //
    // Python: a = [1,2,3]; b = a  — b ссылается на тот же объект
    //         (все переменные в Python — это ссылки!)

    std::cout << "--- 4. Ссылки ---" << std::endl;

    int original{42};
    int& ref = original;  // ref — псевдоним для original

    std::cout << "original = " << original << std::endl;
    std::cout << "ref = " << ref << std::endl;

    ref = 100;  // зменяет original!
    std::cout << "осле ref = 100:" << std::endl;
    std::cout << "  original = " << original << std::endl;
    std::cout << "  ref = " << ref << std::endl;
    std::cout << "  дреса одинаковы: " << &original << " == " << &ref << std::endl;

    // const ссылка — нельзя изменить:
    const int& const_ref = original;
    std::cout << "const_ref = " << const_ref << std::endl;
    // const_ref = 200;  // Ш: нельзя изменить через const ссылку
    std::cout << std::endl;

    // =====================================================================
    // 5. Т vs ССЫ —  Т СЬТЬ
    // =====================================================================
    // ССЫ — предпочтительнее в большинстве случаев:
    //   - араметры функций (const std::string& name)
    //   - огда  нужен nullptr
    //   - огда  нужно переназначать
    //
    // Т — когда нужно:
    //   - пциональное значение (может быть nullptr)
    //   - ереназначение на другой объект
    //   - инамическая память (new/delete)
    //   - ассивы и C-совместимость

    std::cout << "--- 5. казатели vs Ссылки ---" << std::endl;
    std::cout << "Ссылка: простой псевдоним, безопаснее" << std::endl;
    std::cout << "казатель: гибче, но опаснее" << std::endl;
    std::cout << "равило: используйте ссылки, когда можно; указатели, когда нужно" << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 6. СЯ ЯТЬ: new  delete
    // =====================================================================
    //  C++ вы можете выделять память в  (heap) вручную.
    //
    // СТ (stack) — автоматическая память:
    //   int x = 42;  // а стеке, удалится при выходе из {}
    //
    //  (heap) — ручная память:
    //   int* ptr = new int{42};  // ыделяем в куче
    //   delete ptr;              // ЯТЬ освободить!
    //
    // сли забыть delete — Т ЯТ (memory leak)!
    //  Python: сборщик мусора (GC) делает это за вас.
    //  C++: Ы сами отвечаете за память!
    //
    // :  используйте raw new/delete!
    //          спользуйте Ы Т (см. раздел 7)!

    std::cout << "--- 6. new и delete ( рекомендуется!) ---" << std::endl;

    int* heap_int = new int{42};             // ыделяем в куче
    std::cout << "*heap_int = " << *heap_int << std::endl;
    delete heap_int;                          // свобождаем!
    heap_int = nullptr;                       // бнуляем после delete!

    // ассив в куче:
    int* heap_arr = new int[5]{10, 20, 30, 40, 50};
    std::cout << "heap_arr: ";
    for (int i = 0; i < 5; ++i) {
        std::cout << heap_arr[i] << " ";
    }
    std::cout << std::endl;
    delete[] heap_arr;  // delete[] для массивов!
    heap_arr = nullptr;
    std::cout << std::endl;

    // =====================================================================
    // 7. Ы Т (Smart Pointers) — C++11
    // =====================================================================
    // мные указатели ТТС освобождают память!
    // то Ы способ работы с динамической памятью.
    //
    // std::unique_ptr<T> — СТЫ владелец. ельзя копировать!
    //   auto ptr = std::make_unique<int>(42);
    //
    // std::shared_ptr<T> — ЯЫ владелец. Считает ссылки.
    //   амять освобождается, когда последний shared_ptr уничтожается.
    //   auto ptr = std::make_shared<int>(42);
    //
    // Python аналогия: С переменные в Python — это shared_ptr с GC!

    std::cout << "--- 7. мные указатели ---" << std::endl;

    // unique_ptr — единственный владелец:
    {
        auto uptr = std::make_unique<int>(42);
        std::cout << "unique_ptr: *uptr = " << *uptr << std::endl;
        *uptr = 100;
        std::cout << "unique_ptr: *uptr = " << *uptr << std::endl;
        // auto uptr2 = uptr;  // Ш! ельзя копировать!
        auto uptr2 = std::move(uptr);  // ожно ЩТЬ
        std::cout << "осле move: *uptr2 = " << *uptr2 << std::endl;
        // uptr теперь nullptr!
    }  // uptr2 уничтожается, память освобождается автоматически!

    // shared_ptr — разделяемый владелец:
    {
        auto sptr1 = std::make_shared<std::string>("Hello, Smart!");
        std::cout << "shared_ptr: *sptr1 = " << *sptr1 << std::endl;
        std::cout << "use_count = " << sptr1.use_count() << std::endl;

        {
            auto sptr2 = sptr1;  // опирование! Теперь 2 владельца.
            std::cout << "use_count (2 владельца) = " << sptr1.use_count() << std::endl;
        }  // sptr2 уничтожается, но строка жива!

        std::cout << "use_count (1 владелец) = " << sptr1.use_count() << std::endl;
    }  // оследний владелец уничтожен → память освобождена!

    // unique_ptr с вектором:
    auto vec_ptr = std::make_unique<std::vector<int>>(std::vector<int>{1, 2, 3, 4, 5});
    std::cout << "unique_ptr<vector>: ";
    for (const auto& v : *vec_ptr) {
        std::cout << v << " ";
    }
    std::cout << std::endl;
    std::cout << std::endl;

    // =====================================================================
    // 8. ТС : Связанный список на умных указателях
    // =====================================================================
    std::cout << "--- 8. рактический пример ---" << std::endl;

    // ростой пример: обмен значениями через указатели
    int va{10}, vb{20};
    int* pa = &va;
    int* pb = &vb;
    std::cout << "о: *pa = " << *pa << ", *pb = " << *pb << std::endl;

    // бмен значений:
    int temp2 = *pa;
    *pa = *pb;
    *pb = temp2;
    std::cout << "осле обмена: va = " << va << ", vb = " << vb << std::endl;
    std::cout << std::endl;

    std::cout << "========================================" << std::endl;
    std::cout << "  рок 8 завершён!" << std::endl;
    std::cout << "========================================\n" << std::endl;

    std::cout << "Я Я Т:" << std::endl;
    std::cout << "1. апишите функцию, которая возвращает min и max через указатели" << std::endl;
    std::cout << "2. еализуйте динамический массив с new/delete" << std::endl;
    std::cout << "3. ерепишите задание 2 с unique_ptr" << std::endl;
    std::cout << "4. Создайте функцию, принимающую вектор по ссылке" << std::endl;
    std::cout << "5. опробуйте shared_ptr с циклической ссылкой" << std::endl;

    return 0;
}