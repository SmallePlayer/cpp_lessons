// ─────────────────────────────────────────────────────────────────────────────
// ТЯ: то такое C++?
// ─────────────────────────────────────────────────────────────────────────────
//
// C++ — это компилируемый, статически типизированный язык программирования
// общего назначения. н был создан ьёрном Страуструпом в 1979 году как
// расширение языка C.
//
// лючевые особенности C++:
// 1. ТЬСТЬ — C++ компилируется в машинный код, работает очень быстро
// 2. ТЬ ЯТ — вы сами решаете, когда выделять и освобождать память
// 3. ЬТСТЬ — поддерживает процедурное,  и обобщённое
//    программирование
// 4. ССТСТЬ С C — почти весь код на C работает в C++
// 5. СТТЯ Т — богатый набор готовых инструментов (STL)
//
// де используется C++:
// - гры и игровые движки (Unreal Engine)
// - перационные системы (Windows, Linux)
// - раузеры (Chrome, Firefox)
// - азы данных (MySQL, MongoDB)
// - строенные системы и IoT
// - ысокопроизводительные вычисления
// - инансовые приложения (HFT — высокочастотная торговля)
//
// Сравнение с Python:
// ┌─────────────────┬──────────────────┬──────────────────┐
// │ ритерий        │ Python           │ C++              │
// ├─────────────────┼──────────────────┼──────────────────┤
// │ Тип             │ нтерпретируемый │ омпилируемый    │
// │ Типизация       │ инамическая     │ Статическая      │
// │ Скорость        │ едленнее        │ чень быстрый    │
// │ амять          │ втоматическая   │ учная/авто      │
// │ Синтаксис       │ ростой          │ олее сложный    │
// │ омпиляция      │ е нужна         │ бязательна      │
// └─────────────────┴──────────────────┴──────────────────┘
// ─────────────────────────────────────────────────────────────────────────────

// ─────────────────────────────────────────────────────────────────────────────
// ТЯ: иректива #include
// ─────────────────────────────────────────────────────────────────────────────
//
// #include — это директива препроцессора. репроцессор — это программа,
// которая обрабатывает исходный код  компиляции.
//
// #include <iostream>  — подключает заголовочный файл из стандартной библиотеки
// #include "myfile.h"  — подключает ваш собственный заголовочный файл
//
// iostream — это библиотека ввода-вывода (Input/Output Stream).
// на предоставляет объекты:
//   std::cout — вывод в консоль (Console OUTput)
//   std::cin  — ввод с клавиатуры (Console INput)
//   std::endl — перевод строки (END Line)
//   std::cerr — вывод ошибок
//
//  Python: import — подключает модуль во время выполнения
//  C++:    #include — вставляет содержимое файла  компиляции
// ─────────────────────────────────────────────────────────────────────────────

#include <iostream>
#include <string>

// ─────────────────────────────────────────────────────────────────────────────
// ТЯ: ункция main()
// ─────────────────────────────────────────────────────────────────────────────
//
// аждая программа на C++ Я иметь функцию main().
// то точка входа — именно с неё начинается выполнение программы.
//
// int main() {
//     // код программы
//     return 0;  // 0 означает "программа завершилась успешно"
// }
//
// int — тип возвращаемого значения (целое число)
// return 0 — сообщает операционной системе, что всё прошло хорошо
// return 1 (или другое число) — сигнал об ошибке
//
//  Python точки входа нет — код выполняется сверху вниз.
// о есть идиома: if __name__ == "__main__":
//  C++ функция main() — единственная точка входа, она ЯТЬ.
//
// : main() вызывается операционной системой автоматически!
// ы  не должны вызывать main() сами из другого кода.
// ─────────────────────────────────────────────────────────────────────────────

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << "   1: ервая программа на C++" << std::endl;
    std::cout << "========================================" << std::endl;
    std::cout << std::endl;

    // --- 1. Hello, World! ---
    std::cout << "Hello, World!" << std::endl;
    std::cout << "ривет, ир!" << std::endl;
    std::cout << std::endl;

    // --- 2. епочки вывода ---
    std::cout << "--- 2. епочки вывода ---" << std::endl;
    int age = 25;
    std::string name = "лексей";
    std::cout << "мя: " << name << ", озраст: " << age << std::endl;
    std::cout << "то очень длинное сообщение, "
              << "которое разбито на несколько строк "
              << "в исходном коде." << std::endl;
    std::cout << std::endl;

    // --- 3. endl vs \n ---
    std::cout << "--- 3. endl vs \\n ---" << std::endl;
    std::cout << "Строка с endl" << std::endl;
    std::cout << "Строка с \\n\n";
    std::cout << "щё строка с \\n" << '\n';
    std::cout << std::endl;

    // --- 4. омментарии ---
    std::cout << "--- 4. омментарии ---" << std::endl;
    // днострочный комментарий
    /* ногострочный
       комментарий */
    std::cout << "омментарии не влияют на выполнение программы" << std::endl;
    int x = 42; // твет на главный вопрос
    std::cout << "x = " << x << std::endl;
    std::cout << std::endl;

    // --- 5. ространства имён ---
    std::cout << "--- 5. ространства имён ---" << std::endl;
    std::cout << "std::cout — явное указание пространства имён" << std::endl;
    std::cout << "ы всегда пишем std:: явно — это хорошая практика!" << std::endl;
    std::cout << std::endl;

    // --- 6. Escape-последовательности ---
    std::cout << "--- 6. Escape-последовательности ---" << std::endl;
    std::cout << "еренос\nстроки" << std::endl;
    std::cout << "Табуляция:\tвот так" << std::endl;
    std::cout << "братный слэш: \\" << std::endl;
    std::cout << "н сказал: \"ривет!\"" << std::endl;
    std::cout << std::endl;

    // --- 7. вод данных (демо) ---
    std::cout << "--- 7. вод данных ---" << std::endl;
    int demo_number = 42;
    std::cout << "емо: если бы вы ввели число, оно было бы: "
              << demo_number << std::endl;
    std::cout << std::endl;

    // --- 8. азовые типы данных ---
    std::cout << "--- 8. азовые типы данных ---" << std::endl;
    int integer_val = 42;
    double double_val = 3.14159;
    float float_val = 2.71f;
    char char_val = 'A';
    bool bool_val = true;
    std::string string_val = "Hello, C++!";

    std::cout << "int:         " << integer_val << std::endl;
    std::cout << "double:      " << double_val << std::endl;
    std::cout << "float:       " << float_val << std::endl;
    std::cout << "char:        " << char_val << std::endl;
    std::cout << "bool:        " << bool_val << std::endl;
    std::cout << "bool (текст):" << std::boolalpha << bool_val << std::endl;
    std::cout << "string:      " << string_val << std::endl;
    std::cout << std::endl;

    // --- 9. Способы инициализации ---
    std::cout << "--- 9. Способы инициализации ---" << std::endl;
    int a = 10;     // опирующая
    int b(20);      // рямая
    int c{30};      // Списковая — Ы СС
    int d = {40};   // Тоже списковая
    std::cout << "a = " << a << ", b = " << b
              << ", c = " << c << ", d = " << d << std::endl;
    int zero{};
    std::cout << "zero = " << zero << std::endl;
    std::cout << std::endl;

    // --- 10. сегда инициализируйте переменные! ---
    std::cout << "--- 10. нициализация переменных ---" << std::endl;
    int safe_var{0};
    std::cout << "safe_var = " << safe_var << " (инициализирована нулём)" << std::endl;
    std::cout << std::endl;

    std::cout << "========================================" << std::endl;
    std::cout << "  рок 1 завершён!" << std::endl;
    std::cout << "========================================" << std::endl;
    std::cout << std::endl;

    std::cout << "Я Я Т:" << std::endl;
    std::cout << "1. змените приветствие на своё имя" << std::endl;
    std::cout << "2. аскомментируйте код ввода (секция 7) и попробуйте" << std::endl;
    std::cout << "3. Создайте переменные разных типов и выведите их" << std::endl;
    std::cout << "4. опробуйте все 3 способа инициализации" << std::endl;
    std::cout << "5. опробуйте int x{4.5}; — что произойдёт?" << std::endl;

    return 0;
}
