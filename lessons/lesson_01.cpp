// ─────────────────────────────────────────────────────────────────────────────
// ТЕМА: Что такое C++?
// ─────────────────────────────────────────────────────────────────────────────
//
// C++ — это компилируемый, статически типизированный язык программирования
// общего назначения. Он был создан Бьёрном Страуструпом в 1979 году как
// расширение языка C.
//
// Ключевые особенности C++:
// 1. БЫСТРОСТЬ — C++ компилируется в машинный код, работает очень быстро
// 2. КОНТРОЛЬ ПАМЯТИ — вы сами решаете, когда выделять и освобождать память
// 3. МНОГОПАРАДИГМЕННОСТЬ — поддерживает процедурное, ООП и обобщённое
//    программирование
// 4. СОВМЕСТИМОСТЬ С C — почти весь код на C работает в C++
// 5. СТАНДАРТНАЯ БИБЛИОТЕКА — богатый набор готовых инструментов (STL)
//
// Где используется C++:
// - Игры и игровые движки (Unreal Engine)
// - Операционные системы (Windows, Linux)
// - Браузеры (Chrome, Firefox)
// - Базы данных (MySQL, MongoDB)
// - Встроенные системы и IoT
// - Высокопроизводительные вычисления
// - Финансовые приложения (HFT — высокочастотная торговля)
//
// Сравнение с Python:
// ┌─────────────────┬──────────────────┬──────────────────┐
// │ Критерий        │ Python           │ C++              │
// ├─────────────────┼──────────────────┼──────────────────┤
// │ Тип             │ Интерпретируемый │ Компилируемый    │
// │ Типизация       │ Динамическая     │ Статическая      │
// │ Скорость        │ Медленнее        │ Очень быстрый    │
// │ Память          │ Автоматическая   │ Ручная/авто      │
// │ Синтаксис       │ Простой          │ Более сложный    │
// │ Компиляция      │ Не нужна         │ Обязательна      │
// └─────────────────┴──────────────────┴──────────────────┘
// ─────────────────────────────────────────────────────────────────────────────

// ─────────────────────────────────────────────────────────────────────────────
// ТЕМА: Директива #include
// ─────────────────────────────────────────────────────────────────────────────
//
// #include — это директива препроцессора. Препроцессор — это программа,
// которая обрабатывает исходный код ДО компиляции.
//
// #include <iostream>  — подключает заголовочный файл из стандартной библиотеки
// #include "myfile.h"  — подключает ваш собственный заголовочный файл
//
// iostream — это библиотека ввода-вывода (Input/Output Stream).
// Она предоставляет объекты:
//   std::cout — вывод в консоль (Console OUTput)
//   std::cin  — ввод с клавиатуры (Console INput)
//   std::endl — перевод строки (END Line)
//   std::cerr — вывод ошибок
//
// В Python: import — подключает модуль во время выполнения
// В C++:    #include — вставляет содержимое файла ДО компиляции
// ─────────────────────────────────────────────────────────────────────────────

#include <iostream>
#include <string>

// ─────────────────────────────────────────────────────────────────────────────
// ТЕМА: Функция main()
// ─────────────────────────────────────────────────────────────────────────────
//
// Каждая программа на C++ ДОЛЖНА иметь функцию main().
// Это точка входа — именно с неё начинается выполнение программы.
//
// int main() {
//     // код программы
//     return 0;  // 0 означает "программа завершилась успешно"
// }
//
// int — тип возвращаемого значения (целое число)
// return 0 — сообщает операционной системе, что всё прошло хорошо
// return 1 (или другое число) — сигнал об ошибке
//
// В Python точки входа нет — код выполняется сверху вниз.
// Но есть идиома: if __name__ == "__main__":
// В C++ функция main() — единственная точка входа, она ОБЯЗАТЕЛЬНА.
//
// ВАЖНО: main() вызывается операционной системой автоматически!
// Вы НЕ должны вызывать main() сами из другого кода.
// ─────────────────────────────────────────────────────────────────────────────

int main() {
    std::cout << "========================================" << std::endl;
    std::cout << "   Урок 1: Первая программа на C++" << std::endl;
    std::cout << "========================================" << std::endl;
    std::cout << std::endl;

    // --- 1. Hello, World! ---
    std::cout << "Hello, World!" << std::endl;
    std::cout << "Привет, Мир!" << std::endl;
    std::cout << std::endl;

    // --- 2. Цепочки вывода ---
    std::cout << "--- 2. Цепочки вывода ---" << std::endl;
    int age = 25;
    std::string name = "Алексей";
    std::cout << "Имя: " << name << ", Возраст: " << age << std::endl;
    std::cout << "Это очень длинное сообщение, "
              << "которое разбито на несколько строк "
              << "в исходном коде." << std::endl;
    std::cout << std::endl;

    // --- 3. endl vs \n ---
    std::cout << "--- 3. endl vs \\n ---" << std::endl;
    std::cout << "Строка с endl" << std::endl;
    std::cout << "Строка с \\n\n";
    std::cout << "Ещё строка с \\n" << '\n';
    std::cout << std::endl;

    // --- 4. Комментарии ---
    std::cout << "--- 4. Комментарии ---" << std::endl;
    // Однострочный комментарий
    /* Многострочный
       комментарий */
    std::cout << "Комментарии не влияют на выполнение программы" << std::endl;
    int x = 42; // Ответ на главный вопрос
    std::cout << "x = " << x << std::endl;
    std::cout << std::endl;

    // --- 5. Пространства имён ---
    std::cout << "--- 5. Пространства имён ---" << std::endl;
    std::cout << "std::cout — явное указание пространства имён" << std::endl;
    std::cout << "Мы всегда пишем std:: явно — это хорошая практика!" << std::endl;
    std::cout << std::endl;

    // --- 6. Escape-последовательности ---
    std::cout << "--- 6. Escape-последовательности ---" << std::endl;
    std::cout << "Перенос\nстроки" << std::endl;
    std::cout << "Табуляция:\tвот так" << std::endl;
    std::cout << "Обратный слэш: \\" << std::endl;
    std::cout << "Он сказал: \"Привет!\"" << std::endl;
    std::cout << std::endl;

    // --- 7. Ввод данных (демо) ---
    std::cout << "--- 7. Ввод данных ---" << std::endl;
    int demo_number = 42;
    std::cout << "Демо: если бы вы ввели число, оно было бы: "
              << demo_number << std::endl;
    std::cout << std::endl;

    // --- 8. Базовые типы данных ---
    std::cout << "--- 8. Базовые типы данных ---" << std::endl;
    int integer_val = 42;
    double double_val = 3.14159;
    float float_val = 2.71f;
    char char_val = 'A';
    bool bool_val = true;
    std::string string_val = "Hello, C++!";

    std::cout << "int:         " << integer_val << std::endl;
    std::cout << "double:      " << double_val << std::endl;
    std::cout << "float:       " << float_val << std::endl;
    std::cout << "char:        " << char_val << std::endl;
    std::cout << "bool:        " << bool_val << std::endl;
    std::cout << "bool (текст):" << std::boolalpha << bool_val << std::endl;
    std::cout << "string:      " << string_val << std::endl;
    std::cout << std::endl;

    // --- 9. Способы инициализации ---
    std::cout << "--- 9. Способы инициализации ---" << std::endl;
    int a = 10;     // Копирующая
    int b(20);      // Прямая
    int c{30};      // Списковая — РЕКОМЕНДУЕТСЯ
    int d = {40};   // Тоже списковая
    std::cout << "a = " << a << ", b = " << b
              << ", c = " << c << ", d = " << d << std::endl;
    int zero{};
    std::cout << "zero = " << zero << std::endl;
    std::cout << std::endl;

    // --- 10. Всегда инициализируйте переменные! ---
    std::cout << "--- 10. Инициализация переменных ---" << std::endl;
    int safe_var{0};
    std::cout << "safe_var = " << safe_var << " (инициализирована нулём)" << std::endl;
    std::cout << std::endl;

    std::cout << "========================================" << std::endl;
    std::cout << "  Урок 1 завершён!" << std::endl;
    std::cout << "========================================" << std::endl;
    std::cout << std::endl;

    std::cout << "ДОМАШНЕЕ ЗАДАНИЕ:" << std::endl;
    std::cout << "1. Измените приветствие на своё имя" << std::endl;
    std::cout << "2. Раскомментируйте код ввода (секция 7) и попробуйте" << std::endl;
    std::cout << "3. Создайте переменные разных типов и выведите их" << std::endl;
    std::cout << "4. Попробуйте все 3 способа инициализации" << std::endl;
    std::cout << "5. Попробуйте int x{4.5}; — что произойдёт?" << std::endl;

    return 0;
}
